const assert=require('node:assert/strict');
const {DatabaseSync}=require('node:sqlite');
const {createCommunityQuestions}=require('./community-questions.cjs');
const db=new DatabaseSync(':memory:');
db.exec(`PRAGMA foreign_keys=ON;
CREATE TABLE accounts(id TEXT PRIMARY KEY);
CREATE TABLE live_communities(id TEXT PRIMARY KEY,owner_id TEXT,name TEXT,status TEXT,paused INTEGER);
INSERT INTO accounts VALUES('owner'),('visitor'),('other'),('admin');
INSERT INTO live_communities VALUES('open','owner','活動の会','VERIFIED',0),('paused','owner','お休み中','VERIFIED',1);`);
const users={owner:{id:'owner'},visitor:{id:'visitor'},other:{id:'other'},admin:{id:'admin'}};
const notices=[];
const questions=createCommunityQuestions({db,org:id=>{const c=db.prepare('SELECT * FROM live_communities WHERE id=?').get(id);if(!c)throw Object.assign(Error('not found'),{status:404});return c;},blocked:(user,id)=>user?.id==='other'&&id==='open',notify:(...args)=>notices.push(args),isAdmin:user=>user?.id==='admin'});
const fails=(fn,status)=>assert.throws(fn,error=>error.status===status);
assert.equal(questions.list('open',null).canAsk,false);
fails(()=>questions.ask('paused',users.visitor,{body:'参加できますか？'}),404);
fails(()=>questions.ask('open',users.owner,{body:'参加できますか？'}),403);
fails(()=>questions.ask('open',users.other,{body:'参加できますか？'}),404);
const first=questions.ask('open',users.visitor,{body:'初参加でも大丈夫？'});
assert.equal(first.mine.length,1);
assert.equal(first.answered.length,0);
assert.equal(questions.list('open',null).mine.length,0);
assert.equal(questions.list('open',users.owner).mine.length,0);
const inbox=questions.inbox(users.owner).questions;
assert.equal(inbox.length,1);
assert(!Object.hasOwn(inbox[0],'userId'));
fails(()=>questions.answer(inbox[0].id,users.other,{answer:'はい'}),403);
questions.answer(inbox[0].id,users.owner,{answer:'はい、歓迎します。'});
const publicList=questions.list('open',null);
assert.equal(publicList.answered[0].answer,'はい、歓迎します。');
assert(!JSON.stringify(publicList).includes('visitor'));
assert.equal(questions.inbox(users.owner).questions.length,0);
assert.equal(notices.length,2);
questions.hide(inbox[0].id,users.admin);
assert.equal(questions.list('open',null).answered.length,0);
for(let i=0;i<3;i++)questions.ask('open',users.visitor,{body:'質問'+i});
fails(()=>questions.ask('open',users.visitor,{body:'もう一件'}),429);
assert.equal(questions.inbox(users.owner).questions.length,3);
console.log('PASS: community question privacy, publication, ownership, hide, open limit, visibility');
